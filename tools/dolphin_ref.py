"""Dolphin reference chain: runs a game in an isolated Dolphin and stores the captures.

Usage: py -3 tools/dolphin_ref.py <game> [--version ID] [--seconds N] [--frames] [--audio]
                                   [--stop-timeout N] [--keep-user] [--movie F.dtm]
                                   [--user-dir FOLDER] [--no-sound] [--gci-folder FOLDER]

Generic (parameterized by `games/<game>/game.toml`), like the other scripts in `tools/`.

This script NEVER touches the user's personal Dolphin profile
(`%APPDATA%\\Dolphin Emulator`): it creates a dedicated user folder under
`tests/dolphin/<ID>/user/` through Dolphin's official `-u`/`--user` option, and writes the
settings there before launching anything. Verified by a test (see `notes/dolphin.md`,
section "Isolation"): two real launches left no trace in
`%APPDATA%\\Dolphin Emulator`.

Sources of the options and keys used (dolphin-emu/dolphin, master branch, read on 2026-10-09
with WebFetch; `--help` of Dolphin.exe produces no capturable text, since it is a Windows GUI
subsystem application without a console, cf. notes/dolphin.md):
- Command-line options (-u/--user, -e/--exec, -b/--batch, -v/--video_backend, -C/--config,
  -c/--confirm, ...): Source/Core/UICommon/CommandLineParse.cpp
- Dolphin.ini [Movie] DumpFrames / DumpFramesSilent, [DSP] DumpAudio / DumpAudioSilent,
  [Interface] ConfirmStop, [Core] GFXBackend, [AutoUpdate] UpdateTrack,
  [Analytics] Enabled / PermissionAsked: Source/Core/Core/Config/MainSettings.cpp
- GFX.ini [Settings] DumpFramesAsImages / InternalResolution, [Hardware] VSync:
  Source/Core/Core/Config/GraphicsSettings.cpp
- Frame dump as PNG (`framedump_<n>.png`, enabled by DumpFramesAsImages):
  Source/Core/VideoCommon/FrameDumper.cpp
- Names of the audio files (`<ID>_<timestamp>_dspdump.wav`, `..._dtkdump.wav`): observed
  empirically in `Dump/Audio/` during a real run (not found in the source code read).

PAL60 / EuRGB60 (50 Hz vs 60 Hz for PAL games): stored in the emulated GameCube SRAM
(`user/GC/EUR/SRAM.raw`), not in Dolphin.ini. Option renamed "EuRGB60" -> "PAL60" in the
interface (dolphin-emu/dolphin#1281). This script DOES NOT CHANGE this setting: it keeps Dolphin's
default value (SRAM regenerated by Dolphin itself if missing). See meta.json: key
`pal60_changed_by_this_script` always `false`.
"""

from __future__ import annotations

import argparse
import configparser
import datetime
import json
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import extract as ex  # noqa: E402
import toolchain as tc  # noqa: E402

TESTS_DOLPHIN = tc.ROOT / "tests" / "dolphin"


def user_dir_for(game_id: str) -> Path:
    return TESTS_DOLPHIN / game_id / "user"


def _merge_ini(path: Path, sections: dict[str, dict[str, str]]) -> None:
    """Updates only the given keys, keeping the rest of the file if it exists.

    Dolphin reads/writes a standard ini format (section, key = value); configparser fits
    provided interpolation is disabled (values may contain `%`) and the case of the keys is
    preserved (Dolphin is case-sensitive: `DumpFrames`, not `dumpframes`).
    """
    cp = configparser.ConfigParser(interpolation=None)
    cp.optionxform = str  # preserve the case
    if path.exists():
        cp.read(path, encoding="utf-8")
    for section, keys in sections.items():
        if not cp.has_section(section):
            cp.add_section(section)
        for key, value in keys.items():
            cp.set(section, key, value)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        cp.write(f, space_around_delimiters=True)


def prepare_user_dir(user: Path, *, dump_frames: bool, dump_audio: bool, no_sound: bool = False,
                     gci_folder: Path | None = None) -> None:
    """Writes the settings into the isolated user folder (created if missing by Dolphin itself
    on the first launch; we only write the .ini files beforehand, which Dolphin accepts).

    Never a blocking window: [Interface] UsePanicHandlers = False (MAIN_USE_PANIC_HANDLERS,
    Source/Core/Core/Config/MainSettings.cpp; applied by Common::SetEnableAlert in UICommon.cpp). Warning-type
    alerts (PanicAlert, ASSERT_MSG "Ignore and continue?") are then only logged and execution continues
    (Common/MsgHandler.cpp, ShowMessageAlert); questions and critical errors are still shown.
    `no_sound`: nothing on the speakers ([DSP] Backend = "No Audio Output", Volume = 0;
    MAIN_AUDIO_BACKEND / MAIN_AUDIO_VOLUME, BACKEND_NULLSOUND in MainSettings.h).
    Do not write [Core] MemoryCardSize: with the installed Dolphin (2024 build), this key triggered at
    startup the "Default case should not be reached" assertion of GetDirectoryForRegion (modal box seen by
    the human on 2026-10-11, see notes/dolphin.md); the card stays the default one (GCI folder, 2043 blocks).
    `gci_folder`: fixed GCI folder for port A ([Core] GCIFolderAPathOverride, MAIN_GCI_FOLDER_A_PATH_OVERRIDE;
    HW/EXI/EXI_DeviceMemoryCard.cpp GetGCIFolderPath returns it before any path computed from the region or
    the movie): the same card from one launch to the next, movie or not. Without it, the installed Dolphin uses
    GC/<region>/Movie/Card A during a movie."""
    config = user / "Config"
    core = {"GFXBackend": "OGL"}
    if gci_folder is not None:
        core["GCIFolderAPathOverride"] = str(gci_folder)
    dsp = {"DumpAudio": str(dump_audio), "DumpAudioSilent": "True"}
    if no_sound:
        dsp.update({"Backend": "No Audio Output", "Volume": "0"})
    _merge_ini(config / "Dolphin.ini", {
        "Analytics": {"Enabled": "False", "PermissionAsked": "True"},
        "AutoUpdate": {"UpdateTrack": ""},
        "Interface": {"ConfirmStop": "False", "UsePanicHandlers": "False"},
        "Core": core,
        "Movie": {"DumpFrames": str(dump_frames), "DumpFramesSilent": "True"},
        "DSP": dsp,
    })
    _merge_ini(config / "GFX.ini", {
        "Settings": {"DumpFramesAsImages": "True", "InternalResolution": "1"},
        "Hardware": {"VSync": "False"},
    })


def clear_dump_dirs(user: Path) -> None:
    """Empties the dump folders before the launch so as not to mix with a previous run."""
    for sub in ("Dump/Frames", "Dump/Audio", "Dump/DSP"):
        d = user / sub
        if d.exists():
            for f in d.iterdir():
                if f.is_file():
                    f.unlink()


def ensure_iso(game: dict, game_id: str) -> Path:
    image = ex.find_image(game_id)
    if image.suffix.lower() in ex.RAW:
        return image
    work = TESTS_DOLPHIN / "_cache" / game_id
    work.mkdir(parents=True, exist_ok=True)
    return ex.ensure_iso(image, work)


def _natural_key(path: Path):
    return [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", path.name)]


def run_dolphin(dolphin: Path, user: Path, iso: Path, seconds: int, stop_timeout: int,
                 movie: Path | None = None) -> dict:
    cmd = [str(dolphin), "-u", str(user), "-b", "-e", str(iso)]
    if movie:
        cmd += ["-m", str(movie)]
    print("+", " ".join(cmd), flush=True)
    t0 = time.time()
    proc = subprocess.Popen(cmd)
    time.sleep(seconds)
    elapsed_before_stop = time.time() - t0

    stop_method = "graceful"
    subprocess.run(["taskkill", "/PID", str(proc.pid)], capture_output=True, text=True)
    try:
        proc.wait(timeout=stop_timeout)
    except subprocess.TimeoutExpired:
        stop_method = "force"
        subprocess.run(["taskkill", "/PID", str(proc.pid), "/F"], capture_output=True, text=True)
        proc.wait(timeout=stop_timeout)

    return {
        "cmd": cmd,
        "pid": proc.pid,
        "exit_code": proc.returncode,
        "stop_method": stop_method,
        "requested_seconds": seconds,
        "elapsed_seconds_before_stop": round(elapsed_before_stop, 3),
        "total_elapsed_seconds": round(time.time() - t0, 3),
    }


def collect_outputs(user: Path, run_dir: Path, *, dump_frames: bool, dump_audio: bool) -> dict:
    info: dict = {"frame_count": 0, "frame_files": [], "audio_files": []}
    if dump_frames:
        frames_src = user / "Dump" / "Frames"
        frames_dst = run_dir / "frames"
        pngs = sorted(frames_src.glob("*.png"), key=_natural_key) if frames_src.exists() else []
        if pngs:
            frames_dst.mkdir(parents=True, exist_ok=True)
            for p in pngs:
                shutil.move(str(p), str(frames_dst / p.name))
            info["frame_count"] = len(pngs)
            info["frame_files"] = [p.name for p in pngs]
    if dump_audio:
        audio_dst = run_dir / "audio"
        moved = []
        for sub in ("Dump/Audio", "Dump/DSP"):
            src = user / sub
            if not src.exists():
                continue
            for f in sorted(src.iterdir()):
                if f.is_file():
                    audio_dst.mkdir(parents=True, exist_ok=True)
                    shutil.move(str(f), str(audio_dst / f.name))
                    moved.append(f.name)
        info["audio_files"] = moved
    return info


def main() -> int:
    parser = argparse.ArgumentParser(description="Runs a game in an isolated Dolphin for a reference capture.")
    parser.add_argument("game", help="folder in games/ (e.g. chibi-robo)")
    parser.add_argument("--version", help="disc ID (default: default_version from game.toml)")
    parser.add_argument("--seconds", type=int, default=60, help="capture duration in seconds (default: 60)")
    parser.add_argument("--frames", action="store_true", help="dump the frames as PNG (Dump/Frames)")
    parser.add_argument("--audio", action="store_true", help="dump the audio as WAV (Dump/Audio, Dump/DSP)")
    parser.add_argument("--stop-timeout", type=int, default=20,
                         help="seconds to wait after the stop request before a forced stop (default: 20)")
    parser.add_argument("--keep-user", action="store_true",
                         help="do not empty Dump/ before the launch (also keeps the files of a previous run)")
    parser.add_argument("--movie", help=".dtm movie to replay (Dolphin's -m/--movie), for scripted inputs "
                                         "comparable to those of tools/run.py --input on the native side")
    parser.add_argument("--user-dir", help="isolated Dolphin user folder to use (default: "
                                           "tests/dolphin/<ID>/user); its GCI memory card is in GC/<region>/Card A")
    parser.add_argument("--no-sound", action="store_true", help="no sound on the speakers")
    parser.add_argument("--gci-folder", help="fixed GCI folder of the port A card (created if missing)")
    args = parser.parse_args()

    game = tc.load_game(args.game)
    game_id = args.version or game["game"]["default_version"]
    version = next((v for v in game["versions"] if v["game_id"] == game_id), None)
    if version is None:
        raise SystemExit(f"Version {game_id} missing from games/{args.game}/game.toml")

    dolphin = tc.find_dolphin()
    if not dolphin:
        raise SystemExit("Dolphin not found (see config/local.toml [paths] dolphin, or tools/doctor.py).")

    iso = ensure_iso(game, game_id)
    print(f"Image: {iso}")

    user = Path(args.user_dir).resolve() if args.user_dir else user_dir_for(game_id)
    gci = Path(args.gci_folder).resolve() if args.gci_folder else None
    if gci is not None:
        gci.mkdir(parents=True, exist_ok=True)
    prepare_user_dir(user, dump_frames=args.frames, dump_audio=args.audio, no_sound=args.no_sound,
                     gci_folder=gci)
    if not args.keep_user:
        clear_dump_dirs(user)

    movie = Path(args.movie).resolve() if args.movie else None
    run_info = run_dolphin(dolphin, user, iso, args.seconds, args.stop_timeout, movie=movie)
    print(f"Stop: {run_info['stop_method']}, exit code {run_info['exit_code']}, "
          f"total duration {run_info['total_elapsed_seconds']:.1f} s")

    timestamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
    run_dir = TESTS_DOLPHIN / game_id / f"run-{timestamp}"
    run_dir.mkdir(parents=True, exist_ok=True)

    outputs = collect_outputs(user, run_dir, dump_frames=args.frames, dump_audio=args.audio)
    fps_approx = None
    if outputs["frame_count"] and run_info["elapsed_seconds_before_stop"] > 0:
        fps_approx = round(outputs["frame_count"] / run_info["elapsed_seconds_before_stop"], 2)

    meta = {
        "game": args.game,
        "game_id": game_id,
        "region": version.get("region"),
        "revision": version.get("revision"),
        "iso_path": str(iso),
        "dolphin_path": str(dolphin),
        "user_dir": str(user),
        "movie": str(movie) if movie else None,
        "run": run_info,
        "frame_count": outputs["frame_count"],
        "approx_fps_over_requested_duration": fps_approx,
        "audio_files": outputs["audio_files"],
        "options": {
            "video_backend": "OGL",
            "internal_resolution": "1 (native)",
            "vsync": False,
            "dump_frames_as_images": bool(args.frames),
            "dump_audio": bool(args.audio),
            "no_sound": bool(args.no_sound),
            "panic_handlers": False,
            "gci_folder": str(gci) if gci else None,
        },
        "pal60_changed_by_this_script": False,
        "pal60_note": (
            "PAL region: 50/60 Hz (PAL60/EuRGB60) comes from the emulated GameCube SRAM "
            "(user/GC/EUR/SRAM.raw), not from a Dolphin.ini key. Dolphin's default value "
            "kept (not changed by this script)."
            if version.get("region") == "PAL" else None
        ),
        "timestamp": timestamp,
    }
    (run_dir / "meta.json").write_text(json.dumps(meta, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"Captures: {run_dir}")
    print(f"meta.json: {run_dir / 'meta.json'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
