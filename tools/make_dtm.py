"""Generates a minimal Dolphin input movie (.dtm): neutral, then the A button held, then neutral.

Usage:
  py -3 tools/make_dtm.py <game_id> <neutral_before> <frames_A> <neutral_after> <output.dtm>
  e.g.: py -3 tools/make_dtm.py GGTP01 300 1200 1200 tests/dolphin/movies/press_a.dtm
  py -3 tools/make_dtm.py <game_id> --script "BEGIN-END:BUTTONS;..." --total N <output.dtm>
  e.g.: py -3 tools/make_dtm.py GGTP01 --script "300-1500:A;9000-9030:DOWN;9200-9230:A" --total 12000 movie.dtm
     (frames = controller polls, numbered from 0, END excluded; buttons separated by "+":
      A B X Y Z START L R, D-pad UP DOWN LEFT RIGHT, main stick SUP SDOWN SLEFT SRIGHT; neutral elsewhere)

Used to give Dolphin (`-m`/`--movie`, see `notes/dolphin.md`) a scripted input comparable to
`tools/run.py --input` on the native side, to align captures that require pressing a button
(getting past the Health and Safety screen, for example). Generic: does not depend on any specific
game apart from the 6-character ID passed as an argument.

Format checked line by line against Dolphin's official source code (dolphin-emu/dolphin, master
branch, WebFetch 2026-10-09):
- `DTMHeader` (256 bytes, `#pragma pack(push,1)`): Source/Core/Core/Movie.h. Checked by manually
  summing the size of each field = 256, which matches the
  `static_assert(sizeof(DTMHeader) == 256)` of the source file.
- `ControllerState` (8 bytes, `#pragma pack(push,1)`, bit fields): same file. Likewise checked
  by a manual sum (16 bits of flags + 6 bytes = 8), which matches the
  `static_assert(sizeof(ControllerState) == 8)` of the source file.
- `filetype` magic = `'D' 'T' 'M' 0x1A`: `SaveRecording()`/`IsMovieHeader()`, Source/Core/Core/Movie.cpp.
- Check on load (Source/Core/Core/Movie.cpp, `PlayInput`): the `gameID` (first 6 characters)
  **must** match the loaded image, otherwise Dolphin shows a blocking dialog box
  (`PanicAlertFmtT`); this is why `gameID` is a mandatory parameter of this script.
  The other header settings (bDSPHLE, bProgressive, bWii...) are only informational metadata:
  they are applied at launch only if `bSaveConfig` is true, which this script always sets to 0
  so as never to change the current Dolphin configuration.

**Exact bit layout of `ControllerState` verified by an actual compilation**, not only read in the
source code (C++ does not guarantee the bit order of a bit-field structure): a small program
reproducing the structure was compiled with the same compiler (MSVC, the repository's one through
`tools/toolchain.py:msvc_env()`) and run to observe the bytes actually produced.
Result (see `notes/dolphin.md` for the details):
  byte 0: bit0=Start bit1=A bit2=B bit3=X bit4=Y bit5=Z bit6=DPadUp bit7=DPadDown
  byte 1: bit0=DPadLeft bit1=DPadRight bit2=L bit3=R bit4=disc bit5=reset bit6=is_connected bit7=get_origin
  bytes 2-7: TriggerL, TriggerR, AnalogStickX, AnalogStickY, CStickX, CStickY (0x80 = stick centered)

**Verified end to end by a real run** (not only by construction): a movie generated by this script
was replayed with Dolphin (`-u <isolated folder> -b -e <iso> -m <movie>`) and did make Chibi-Robo!
progress past the health and safety warning screen (which only advances on a button press) up to
the title screen. Details, trials and timing: `notes/dolphin.md`.
"""

from __future__ import annotations

import argparse
import struct
import sys
from pathlib import Path


def controller_frame(*, a: bool = False, connected: bool = True) -> bytes:
    byte0 = (1 << 1) if a else 0
    byte1 = (1 << 6) if connected else 0
    return bytes([byte0, byte1, 0, 0, 0x80, 0x80, 0x80, 0x80])


# Buttons -> (byte, bit) from the layout verified above (docstring); stick: (axis, value).
BUTTON_BITS = {"START": (0, 0), "A": (0, 1), "B": (0, 2), "X": (0, 3), "Y": (0, 4), "Z": (0, 5),
               "UP": (0, 6), "DOWN": (0, 7), "LEFT": (1, 0), "RIGHT": (1, 1), "L": (1, 2), "R": (1, 3)}
STICK = {"SLEFT": (4, 0x00), "SRIGHT": (4, 0xFF), "SUP": (5, 0xFF), "SDOWN": (5, 0x00)}


def frame_with(buttons: list[str]) -> bytes:
    """Controller state (port 0 connected) with the given buttons held."""
    f = bytearray(controller_frame())
    for b in buttons:
        if b in BUTTON_BITS:
            byte, bit = BUTTON_BITS[b]
            f[byte] |= 1 << bit
        elif b in STICK:
            axis, value = STICK[b]
            f[axis] = value
        else:
            raise ValueError(f"unknown button: {b!r} (known: {', '.join([*BUTTON_BITS, *STICK])})")
    return bytes(f)


def frames_from_script(script: str, total: int) -> list[bytes]:
    """`BEGIN-END:A+B;...` (polls, END excluded) -> list of `total` states, neutral outside the segments."""
    frames = [controller_frame()] * total
    for seg in filter(None, (s.strip() for s in script.split(";"))):
        span, _, buttons = seg.partition(":")
        lo, _, hi = span.partition("-")
        lo, hi = int(lo), int(hi or int(lo) + 1)
        if not (0 <= lo < hi <= total):
            raise ValueError(f"segment outside the movie: {seg!r} (total {total})")
        state = frame_with([b.strip().upper() for b in buttons.split("+") if b.strip()])
        for i in range(lo, hi):
            frames[i] = state
    return frames


def build_header(game_id: bytes, frame_count: int) -> bytes:
    if len(game_id) != 6:
        raise ValueError(f"game_id must be exactly 6 characters, got {game_id!r}")
    h = bytearray(256)
    h[0:4] = b"DTM\x1a"
    h[4:10] = game_id
    h[10] = 0          # bWii = False (GameCube)
    h[11] = 0x01       # controllers: bit0 = GameCube pad on port 0 connected
    h[12] = 0          # bFromSaveState = False
    struct.pack_into("<Q", h, 13, frame_count)   # frameCount
    struct.pack_into("<Q", h, 21, frame_count)   # inputCount (no slowdown/"lag" distinguished here)
    struct.pack_into("<Q", h, 29, 0)             # lagCount
    struct.pack_into("<Q", h, 37, 0)             # uniqueID
    struct.pack_into("<I", h, 45, 0)             # numRerecords
    author = b"dolphin_ref_make_dtm\x00"
    h[49:49 + len(author)] = author
    # videoBackend (81..97), audioEmulator (97..113), md5 (113..129): left at zero (not checked).
    struct.pack_into("<Q", h, 129, 0)  # recordingStartTime
    h[137] = 0  # bSaveConfig = False: NEVER changes the current Dolphin configuration on load
    # tickCount (u64 at 237 = 256 - reserved2[11] - 8): Dolphin stops playing the movie as soon as the emulated
    # ticks exceed this value (Movie.cpp, MovieManager::CheckInputEnd). At 0, the movie stopped immediately and
    # NO input was applied (observed on 2026-10-11, notes/dolphin.md): maximum value, the end of the movie
    # is then given by the end of the input data (m_current_byte >= size).
    struct.pack_into("<Q", h, 237, 0xFFFFFFFFFFFFFFFF)
    # Everything else (bEFB*, memcards, bPAL60, language, bFollowBranch, etc.) stays at 0 (default
    # values) since bSaveConfig = False makes them ineffective.
    assert len(h) == 256
    return bytes(h)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generates a .dtm movie for Dolphin (neutral / A held / neutral, or a script of segments).")
    parser.add_argument("game_id", help="6-character disc ID, e.g. GGTP01 (must match the loaded ISO)")
    parser.add_argument("rest", nargs="+", help="<neutral_before> <frames_A> <neutral_after> <output.dtm>, "
                                                "or only <output.dtm> with --script and --total")
    parser.add_argument("--script", help='"BEGIN-END:BUTTONS" segments separated by ";" (see the module help)')
    parser.add_argument("--total", type=int, help="total number of frames in the movie (with --script)")
    args = parser.parse_args()

    game_id = args.game_id.encode("ascii")
    if args.script is not None:
        if len(args.rest) != 1 or not args.total:
            parser.error("with --script: a single <output.dtm> argument and --total N")
        out = Path(args.rest[0])
        frames = frames_from_script(args.script, args.total)
        summary = f'script "{args.script}"'
    else:
        if len(args.rest) != 4:
            parser.error("expected: <neutral_before> <frames_A> <neutral_after> <output.dtm>")
        before, press, after = (int(x) for x in args.rest[:3])
        out = Path(args.rest[3])
        frames = [controller_frame(a=False)] * before + [controller_frame(a=True)] * press +             [controller_frame(a=False)] * after
        summary = f"{before} neutral, {press} A held, {after} neutral"
    header = build_header(game_id, len(frames))
    body = b"".join(frames)

    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("wb") as f:
        f.write(header)
        f.write(body)
    print(f"Wrote {out}: {len(frames)} frames ({summary}), {len(header) + len(body)} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
