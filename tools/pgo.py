"""Profile-guided optimization (PGO) profiles of our builds: production, verification, staleness (generic).

The profiles (LLVM .profdata, .profraw) never go into Git (project policy, see README.md): they only serve our builds
and stay local. The reference profile of a game version is the one that `train` writes into build/pgo/<game>-<ID>/
(profile.profdata and profile-info.json); tools/build.py --pgo auto uses it if it is up to date.

Usage:
  py -3 tools/pgo.py <game> train [--version ID] [--tag T] [--scenarios a,b] [--clang PATH]
        instrumented build (build/<game>-<ID>-Release[-<tag>]-pgogen), replay of the training scenarios
        ([pgo] scenarios from games/<game>/game.toml, cycle clock, hence reproducible), merge with llvm-profdata;
        writes the profile and its profile-info.json into build/pgo/<game>-<ID>/
  py -3 tools/pgo.py <game> check [--version ID] [--dir FOLDER]
        readable and non-empty profile (summary from llvm-profdata show), file matching profile-info.json (SHA-1) and
        staleness (profile-info.json compared with the current code) of the profile in FOLDER (default:
        build/pgo/<game>-<ID>/); exit code 1 otherwise
  py -3 tools/pgo.py <game> show [--version ID] [--dir FOLDER]      profile-info.json, then the checks of check

A profile contains counters and structural hashes per function of the compiled C code (code generated by DolRecomp
and C code of the runtime), under the name of each function. It is only valid for the exact code it was trained on:
tools/build.py --pgo auto only uses it if profile-info.json matches the current code and compiler, and after the build
counts the functions whose profile clang considers out of date (-Wprofile-instr-out-of-date; expected: 0).

Description of the profile (profile-info.json, format gcrt-pgo-info/1):
  format                                  gcrt-pgo-info/1
  game, version, iso_sha1                 game, disc ID, image fingerprint from game.toml
  config                                  build configuration (Release)
  profile, profile_sha1                   name of the profile file and its SHA-1
  fingerprints.generated_code             generated code (DOL and REL, DolRecomp executable and commit with its patches,
                                          hooks, symbol map): the one that decides its regeneration (tools/build.py)
  fingerprints.runtime                    content of the sources compiled around it (generic runtime, game code and
                                          CMake, root CMake, Aurora commit)
  compiler.llvm, .target, .description    LLVM version, target (triple) and version line of the clang that produced it
                                          (the .profdata format depends on the LLVM version: same version and same
                                          target required)
  commits.repo, .dolrecomp, .aurora       current commits ("+fingerprint" if the tree was modified), for traceability
  scenarios                               training scenarios (name, sha1 fingerprint of the scenario: tools/scenario.py)
  date, training_s                        production date, duration of the replay
  content.functions                       number of functions in the profile
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import scenario as scn  # noqa: E402
import toolchain as tc  # noqa: E402

INFO_FORMAT = "gcrt-pgo-info/1"
PROFILE_NAME = "profile.profdata"
INFO_NAME = "profile-info.json"
CONFIG = "Release"  # only trained configuration (and the only one used by tools/build.py --pgo auto)


# --- LLVM tools -----------------------------------------------------------------------------------------------------
# The .profdata format depends on the LLVM version: a profile can only be used by a clang of the same version (and the
# same target) as the one that produced it. `compiler`: explicit clang (e.g. another LLVM install); default: the
# development one (tools/toolchain.py). llvm-profdata and the profiling runtime are looked up in the same LLVM
# install.

def default_compiler() -> Path | None:
    return tc.find_clang_cl()


def find_profile_runtime(compiler: Path | None = None) -> Path | None:
    """clang profiling runtime shipped with LLVM (lib/clang/<version>/lib/windows/clang_rt.profile-x86_64.lib)."""
    compiler = compiler or default_compiler()
    if not compiler:
        return None
    libs = sorted((compiler.parent.parent / "lib" / "clang").glob("*/lib/windows/clang_rt.profile-x86_64.lib"))
    return libs[-1] if libs else None


def find_llvm_profdata(compiler: Path | None = None) -> Path | None:
    compiler = compiler or default_compiler()
    exe = compiler.parent / f"llvm-profdata{tc.EXE}" if compiler else None
    return exe if exe and exe.exists() else None


def compiler_identity(compiler: Path | None = None) -> dict:
    """LLVM version and target (triple) of the compiler, from `clang --version`."""
    compiler = compiler or default_compiler()
    if not compiler:
        return {"llvm": "?", "target": "?", "description": "?"}
    out = subprocess.run([str(compiler), "--version"], capture_output=True, text=True).stdout
    m = re.search(r"clang version (\S+)", out)
    t = re.search(r"^Target: (\S+)", out, re.M)
    first = out.splitlines()[0].strip() if out else "?"
    return {"llvm": m.group(1) if m else "?", "target": t.group(1) if t else "?", "description": first}


# --- Locations and fingerprints -------------------------------------------------------------------------------------

def local_dir(game: str, version: str) -> Path:
    """Folder of the reference profile of a version (written by train, read by default by select, check and show)."""
    return tc.ROOT / "build" / "pgo" / f"{game}-{version}"


def recomp_digest(state: dict) -> str:
    """Fingerprint of the generated code (the one that decides its regeneration in tools/build.py: DOL, REL,
    DolRecomp, patches, hooks, symbol map)."""
    return hashlib.sha1(json.dumps(state.get("fingerprint"), sort_keys=True).encode()).hexdigest()[:16]


RUNTIME_SUFFIXES = {".c", ".h", ".cpp", ".hpp", ".in", ".cmake", ".txt", ".tsv"}


def runtime_digest(game: str) -> str:
    """Fingerprint of the code compiled around the generated code: sources of the generic runtime, C/C++ code and CMake
    of the game, root CMake, Aurora commit (the C libraries it brings). Independent of Git (computed on the content)."""
    h = hashlib.sha1()
    files = [p for p in (tc.ROOT / "runtime").rglob("*") if p.is_file() and p.suffix in RUNTIME_SUFFIXES]
    gdir = tc.ROOT / "games" / game
    files += [p for p in gdir.glob("*") if p.is_file() and (p.suffix in {".c", ".h", ".cpp", ".hpp"} or
                                                             p.name == "CMakeLists.txt")]
    files.append(tc.ROOT / "CMakeLists.txt")
    for p in sorted(set(files)):
        h.update(p.relative_to(tc.ROOT).as_posix().encode() + b"\0")
        h.update(p.read_bytes().replace(b"\r\n", b"\n") + b"\0")
    h.update(git_head(tc.EXTERNAL / "aurora").encode())
    return h.hexdigest()[:16]


def git_head(repo: Path) -> str:
    git = tc.find_git()
    if not git or not (repo / ".git").exists():
        return "?"
    head = subprocess.run([str(git), "-C", str(repo), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    diff = subprocess.run([str(git), "-C", str(repo), "diff", "HEAD"], capture_output=True).stdout
    return (head or "?") + ("+" + hashlib.sha1(diff).hexdigest()[:12] if diff else "")


def current_identity(game: str, version: str, state: dict, compiler: Path | None = None) -> dict:
    return {"fingerprints": {"generated_code": recomp_digest(state), "runtime": runtime_digest(game)},
            "compiler": compiler_identity(compiler)}


# Beginnings of the reasons that make a profile unusable (and not only stale): see select().
INCOMPATIBLE_LLVM = "incompatible LLVM version"
INCOMPATIBLE_TARGET = "different compiler target"


def staleness(info: dict, current: dict) -> list[str]:
    """Differences that make a profile unusable or stale (empty list: up to date). Compiler: same LLVM version and
    same target required (the profile format depends on them)."""
    out = []
    labels = {"generated_code": "generated code (DOL/REL, DolRecomp, patches, hooks)", "runtime": "runtime sources"}
    for k, label in labels.items():
        a, b = info.get("fingerprints", {}).get(k), current["fingerprints"].get(k)
        if a != b:
            out.append(f"{label}: profile {a} / current {b}")
    fc, cc = info.get("compiler", {}), current["compiler"]
    if fc.get("llvm") != cc.get("llvm"):
        out.append(f"{INCOMPATIBLE_LLVM}: profile produced by {fc.get('llvm')}, compiler {cc.get('llvm')}")
    if fc.get("target") != cc.get("target"):
        out.append(f"{INCOMPATIBLE_TARGET}: profile {fc.get('target')}, compiler {cc.get('target')}")
    return out


# --- Reading the profile --------------------------------------------------------------------------------------------
# Simple check: the merge produced a readable and non-empty profile (number of functions recorded in the info file).
# The content check against a closed list of the lines of `llvm-profdata show --all-functions` (a gate before committing
# a profile to the repository) was removed on 2026-10-12: profiles no longer go into Git, and that list wrongly rejected
# those of an LLVM version that adds a field to its output (LLVM 23: `instrument_loop_entries`).

_TOTAL_FUNCTIONS = re.compile(r"^Total functions: (\d+)$", re.M)


def profile_functions(profile: Path, compiler: Path | None = None) -> tuple[int, str | None]:
    """(number of functions, problem or None) from the summary of `llvm-profdata show` ("Total functions" line)."""
    profdata = find_llvm_profdata(compiler)
    if not profdata:
        return 0, "llvm-profdata not found"
    r = subprocess.run([str(profdata), "show", str(profile)], capture_output=True, text=True, errors="replace")
    if r.returncode != 0:
        return 0, f"llvm-profdata show failed: {r.stderr.strip()[:300]}"
    m = _TOTAL_FUNCTIONS.search(r.stdout)
    if not m:
        return 0, 'llvm-profdata show summary without a "Total functions" line'
    functions = int(m.group(1))
    return functions, None if functions else "no function in the profile"


# --- Production -----------------------------------------------------------------------------------------------------

def train(game: str, version: str, tag: str | None, scenarios: list[str], jobs: int | None = None,
          compiler: Path | None = None) -> Path:
    """Produces the local reference profile (build/pgo/<game>-<ID>/); returns its folder."""
    import build  # tools/build.py (late import: build also imports this module)

    runtime, profdata = find_profile_runtime(compiler), find_llvm_profdata(compiler)
    if not runtime or not profdata:
        raise SystemExit(f"PGO: clang_rt.profile-x86_64.lib or llvm-profdata not found next to "
                         f"{compiler or default_compiler()}.")
    game_cfg = tc.load_game(game)
    names = scenarios or game_cfg.get("pgo", {}).get("scenarios", [])
    if not names:
        raise SystemExit(f"PGO: no training scenario ([pgo] scenarios in games/{game}/game.toml).")
    out = local_dir(game, version)
    out.mkdir(parents=True, exist_ok=True)
    disc_root, recomp_dir, state = build.prepare(game, game_cfg, version, force_recomp=False, no_symbols=False, jobs=jobs)
    print(f"== PGO 1/3: instrumented build ({version})")
    gen_exe = build.configure_and_build(game, version, CONFIG, disc_root, recomp_dir, state, jobs,
                                        f"{tag}-pgogen" if tag else "pgogen", pgo=("GENERATE", runtime),
                                        compiler=compiler)
    raw = out / "raw"
    shutil.rmtree(raw, ignore_errors=True)
    raw.mkdir(parents=True)
    env = dict(os.environ)
    env["LLVM_PROFILE_FILE"] = str(raw / "%p-%m.profraw")  # %p: process, %m: module (clang documentation)
    used = []
    t0 = time.perf_counter()
    for name in names:
        print(f"== PGO 2/3: training, scenario {name}")
        run_dir = out / "runs" / name
        shutil.rmtree(run_dir, ignore_errors=True)
        cmd = [sys.executable, tc.ROOT / "tools" / "run.py", game, "--version", version, "--exe", gen_exe,
               "--scenario", name, "--out", run_dir]
        build.run_logged(cmd, out / f"train-{name}.log", env=env)
        used.append({"name": name, "sha1": scenario_sha1(game, version, name)})
    train_s = time.perf_counter() - t0
    profraws = sorted(raw.glob("*.profraw"))
    if not profraws:
        raise SystemExit(f"PGO: no raw profile written in {raw}.")
    print(f"== PGO 3/3: merging {len(profraws)} raw profile(s)")
    profile = out / PROFILE_NAME
    # The old description is removed before the merge overwrites the profile: without it, a profile is never used
    # (load_info), so a failed merge does not leave an old description next to a new or partial profile.
    (out / INFO_NAME).unlink(missing_ok=True)
    build.run_logged([profdata, "merge", "-o", profile, *profraws], out / "merge.log")
    shutil.rmtree(raw, ignore_errors=True)
    nfun, problem = profile_functions(profile, compiler)
    if problem:
        raise SystemExit(f"PGO: unusable profile ({problem}); kept without {INFO_NAME} in {profile}, so never used.")
    info = {
        "format": INFO_FORMAT,
        "game": game,
        "version": version,
        "iso_sha1": next((v.get("iso_sha1") for v in game_cfg.get("versions", []) if v.get("game_id") == version), None),
        "config": CONFIG,
        "profile": PROFILE_NAME,
        "profile_sha1": build.sha1_file(profile),
        **current_identity(game, version, state, compiler),
        "commits": {"repo": git_head(tc.ROOT), "dolrecomp": git_head(tc.EXTERNAL / "DolRecomp"),
                    "aurora": git_head(tc.EXTERNAL / "aurora")},
        "scenarios": used,
        "date": time.strftime("%Y-%m-%d %H:%M:%S"),
        "training_s": round(train_s, 1),
        "content": {"functions": nfun},
    }
    (out / INFO_NAME).write_text(json.dumps(info, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    print(f"   profile: {profile} ({profile.stat().st_size / 1e6:.1f} MB, {nfun} functions, training {train_s:.0f} s);"
          f" local (never in Git), used by tools/build.py --pgo auto as long as it is up to date")
    return out


def scenario_sha1(game: str, version: str, name: str) -> str | None:
    """Fingerprint of the scenario (interpreted content, tools/scenario.py), None if it is not found."""
    try:
        return scn.load(name, game, tc.ROOT, version).sha1
    except scn.ScenarioError:
        return None


# --- Choosing the profile for a build (tools/build.py) ---------------------------------------------------------------

def load_info(directory: Path) -> dict | None:
    f = directory / INFO_NAME
    if not f.exists() or not (directory / PROFILE_NAME).exists():
        return None
    try:
        return json.loads(f.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def select(game: str, version: str, config: str, state: dict, directory: Path | None,
           require_fresh: bool) -> tuple[Path | None, str]:
    """Profile to use (or None) and message to print. `directory`: default, the local reference profile
    (build/pgo/<game>-<ID>/). `require_fresh`: reject a stale profile (auto mode)."""
    d = directory or local_dir(game, version)
    regen = f"py -3 tools/pgo.py {game} train --version {version}"
    without = "build without PGO (same behavior, only slower)"
    info = load_info(d)
    if info is None:
        return None, f"no PGO profile in {d}: {without}; to produce one: {regen}"
    if config != info.get("config", CONFIG):
        return None, f"PGO profile of configuration {info.get('config')} ({d}): {config} build without PGO"
    if info.get("version") != version:
        return None, f"PGO profile of another version ({info.get('version')}, {d}): {without}"
    profile = d / info.get("profile", PROFILE_NAME)
    stale = staleness(info, current_identity(game, version, state))
    incompatible = [x for x in stale if x.startswith((INCOMPATIBLE_LLVM, INCOMPATIBLE_TARGET))]
    if incompatible:
        return None, f"unusable PGO profile ({'; '.join(incompatible)}, {d}): {without}; regenerate: {regen}"
    if stale and require_fresh:
        return None, f"stale PGO profile ({'; '.join(stale)}, {d}): {without}; regenerate: {regen}"
    note = f"PGO profile {profile} (trained on {info.get('date', '?')})"
    if stale:
        note += " — STALE: " + "; ".join(stale)
    return profile, note


_OUT_OF_DATE = re.compile(r"profile data may be out of date: of (\d+) functions?, (\d+) (?:has|have) mismatched data")


def count_out_of_date(build_log: Path) -> dict:
    """Functions with a stale profile, from the clang warnings (-Wprofile-instr-out-of-date) in the log."""
    files = functions = mismatched = 0
    if build_log.exists():
        for m in _OUT_OF_DATE.finditer(build_log.read_text(encoding="utf-8", errors="replace")):
            files += 1
            functions += int(m.group(1))
            mismatched += int(m.group(2))
    return {"files": files, "stale_functions": mismatched, "functions_in_files": functions}


# --- Command line ---------------------------------------------------------------------------------------------------

def main() -> int:
    ap = argparse.ArgumentParser(description="Local PGO profiles of our builds: production, verification, "
                                             "staleness (never in Git).")
    ap.add_argument("game")
    ap.add_argument("action", choices=["train", "check", "show"])
    ap.add_argument("--version")
    ap.add_argument("--tag", help="suffix of the build folders (like tools/build.py --tag)")
    ap.add_argument("--scenarios", help="comma-separated training scenarios (default: [pgo] from game.toml)")
    ap.add_argument("--dir", help="folder of the profile to check (default: local profile build/pgo/<game>-<ID>/)")
    ap.add_argument("--jobs", type=int)
    ap.add_argument("--clang", help="explicit compiler (clang-cl) to produce or check the profile; default: the "
                                    "development one")
    a = ap.parse_args()
    compiler = Path(a.clang).resolve() if a.clang else None
    game_cfg = tc.load_game(a.game)
    version = a.version or game_cfg["game"]["default_version"]
    if a.action == "train":
        train(a.game, version, a.tag, [s for s in (a.scenarios or "").split(",") if s], a.jobs, compiler)
        return 0
    d = Path(a.dir).resolve() if a.dir else local_dir(a.game, version)
    info = load_info(d)
    if info is None:
        print(f"No profile in {d} (to produce one: py -3 tools/pgo.py {a.game} train --version {version}).")
        return 1
    if a.action == "show":
        print(json.dumps(info, indent=2, ensure_ascii=False))
    nfun, problem = profile_functions(d / info.get("profile", PROFILE_NAME), compiler)
    print(f"profile: {'readable' if problem is None else 'UNUSABLE: ' + problem} ({nfun} functions)")
    import build
    state_path = tc.GENERATED / a.game / version / "recomp" / "state.json"
    if not state_path.exists():
        print("staleness: generated code missing (run tools/build.py): not checked")
        return 1
    stale = staleness(info, current_identity(a.game, version, json.loads(state_path.read_text(encoding="utf-8")), compiler))
    sha_ok = build.sha1_file(d / info.get("profile", PROFILE_NAME)) == info.get("profile_sha1")
    print("staleness: " + ("up to date" if not stale else "STALE: " + "; ".join(stale)))
    print("file fingerprint: " + (f"matches {INFO_NAME}" if sha_ok else f"DIFFERS from {INFO_NAME}"))
    return 0 if problem is None and not stale and sha_ok else 1


if __name__ == "__main__":
    sys.exit(main())
