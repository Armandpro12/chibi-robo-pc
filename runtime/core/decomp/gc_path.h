// gc_path.h: cost by path of a decompiled function (generic, no game here).
//
// Why: on the cycle clock (gc_abi.h "Guest time"), each call of a decompiled function charges the guest cycles its
// recompiled original would have spent. When the original's cost depends on the path it takes (a test that returns
// early, a list walked to its end), a mean cost is right only on average: the guest time drifts call by call, and the
// game's busy-wait loops absorb the drift in whole turns, so the run no longer matches the recompiled game cycle for
// cycle. Cost by path charges each call the exact cycles of the path the original would have taken.
//
// How: the build reads, from the code DolRecomp generated for the original, the cycle charge of each cost group
// (`ctx->downcount -= N` at the head of a group) and the original's branches, and makes a small graph of its
// conditional branches (tools/decomp_path_cost.py; table generated in the build folder, never written by hand):
// an entry edge, then for each conditional branch the cycles until the next one (or the return) on each side. The
// decompiled code says, at each of the original's conditional branches and in the original's order, whether that
// branch is taken: gc::path::taken(c) (the branch is taken when `c` holds) or gc::path::falls_through(c) (the branch
// is NOT taken when `c` holds). Both return `c` unchanged, so they sit inside the conditions the code already has:
//
//     if (gc::path::taken(object == nullptr)) // original: beq to its "return 0"
//         return 0;
//
// The gateway walks the graph with these outcomes and charges the sum at the end of the call; a walk that does not
// end exactly on a return of the original is a path error (counted in the exit report, DECOMP path_cost, and the
// table's mean cost is charged instead). The oracle compares the cost of the walk with the exclusive cycles the
// original really spent, on every compared call (gc_oracle.cpp, path_checked / path_mismatches).
//
// Outside of a walk the markers record nothing: in a function without a graph (constant cost), or without the gateway
// (native memory, D4; tests), they are plain conditions. They go at D3 with the cycle clock coupling: they then become
// identity functions and can be removed by a script, the conditions stay as they are.
#ifndef GC_PATH_H
#define GC_PATH_H

#include <cstdint>

namespace gc::abi {

// Graph of the conditional branches of one original (generated by the build, gc_abi.h registration::path).
// `next`: index of the next conditional branch in `nodes`, or path_return when the edge ends on a return of the
// original (blr, a taken bclr, or a tail branch out of the function).
inline constexpr std::uint32_t path_return = 0xFFFFFFFFu;
struct path_edge {
    std::uint32_t cycles; // charges of the cost groups run along the edge
    std::uint32_t next;
};
struct path_node {
    std::uint32_t address; // guest address of the conditional branch (messages only)
    path_edge taken;
    path_edge not_taken;
};
struct path_graph {
    path_edge entry;
    std::uint32_t node_count;
    const path_node* nodes;
};

namespace detail {

// Walk of the graph of the function that runs (one per call, on the C++ stack of the gateway; nested calls of other
// decompiled functions have their own and restore this one). `steps` counts the outcomes recorded.
struct path_walk {
    const path_graph* graph = nullptr;
    std::uint32_t node = path_return;
    std::uint64_t cycles = 0;
    std::uint32_t steps = 0;
    bool error = false; // an outcome came after the walk had reached a return
};
#if !defined(GC_NATIVE_MEMORY)
extern path_walk* current_path; // nullptr: no walk (function without a graph, or outside the gateway)
#endif

inline void path_step(bool branch_taken) noexcept {
#if !defined(GC_NATIVE_MEMORY)
    path_walk* w = current_path;
    if (!w)
        return;
    w->steps++;
    if (w->node == path_return) {
        w->error = true;
        return;
    }
    const path_node& n = w->graph->nodes[w->node];
    const path_edge& e = branch_taken ? n.taken : n.not_taken;
    w->cycles += e.cycles;
    w->node = e.next;
#else
    (void)branch_taken;
#endif
}

} // namespace detail
} // namespace gc::abi

namespace gc::path {

// The original's next conditional branch is taken when `condition` holds. Returns `condition`.
template <class C> inline C taken(C condition) noexcept {
    ::gc::abi::detail::path_step(static_cast<bool>(condition));
    return condition;
}

// The original's next conditional branch is NOT taken (falls through) when `condition` holds. Returns `condition`.
template <class C> inline C falls_through(C condition) noexcept {
    ::gc::abi::detail::path_step(!static_cast<bool>(condition));
    return condition;
}

} // namespace gc::path

#endif // GC_PATH_H
